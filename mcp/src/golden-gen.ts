// Prints the tool schemas as a client sees them (tools/list over an in-memory connection), for
// mcp/tool-schemas.golden.json. Used by scripts/gen-mcp-golden.js and by the golden test, so there is one way to make it.
import { Client, InMemoryTransport } from "@modelcontextprotocol/client"
import { Bridge } from "./bridge"
import { ErrorCodes } from "./errors"
import type { HostConnector } from "./host"
import { Scrubber } from "./scrub"
import { createServer } from "./server"
import { BridgeName, SupportedSpecRevisions } from "./version"

/** Keys sorted all the way down, so the file is stable */
function sortKeys(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(sortKeys)
  if (value !== null && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value as Record<string, unknown>)
        .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
        .map(([k, v]) => [k, sortKeys(v)])
    )
  }
  return value
}

const neverConnects: HostConnector = {
  kind: "golden",
  connect: () => Promise.reject(new Error("the golden generator never connects")),
  dispose: () => undefined,
}

export async function currentToolSchemas(): Promise<unknown> {
  const bridge = new Bridge({ connector: neverConnects, scrubber: new Scrubber() })
  const [clientSide, serverSide] = InMemoryTransport.createLinkedPair()
  const server = createServer(bridge)
  await server.connect(serverSide)
  const client = new Client({ name: "golden", version: "0" })
  await client.connect(clientSide)
  const listed = await client.listTools()
  await client.close()
  await server.close()
  const tools = listed.tools.map((t) => ({
    name: t.name,
    title: t.title,
    description: t.description,
    annotations: t.annotations,
    inputSchema: t.inputSchema,
    outputSchema: t.outputSchema,
  }))
  return sortKeys({
    note: `Generated by npm run mcp:golden from ${BridgeName}'s tools/list. A change here is a change to what agents see: review it, and bump the bridge's major version for a breaking one.`,
    specRevisions: [...SupportedSpecRevisions],
    errorCodes: [...ErrorCodes],
    tools,
  })
}

export function goldenText(schemas: unknown): string {
  return JSON.stringify(schemas, null, 2) + "\n"
}
